let currentLang='ar';
try{ const saved=localStorage.getItem('mm_lang'); if(saved&&['ar','fr','en'].indexOf(saved)>=0) currentLang=saved; }catch(e){}
const html=document.documentElement;

function applyLanguage(lang){
  if(['ar','fr','en'].indexOf(lang)<0) lang='ar';
  currentLang=lang;
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const k=el.getAttribute('data-i18n'),e=T[k]; if(!e) return;
    el.innerHTML=e[lang];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const k=el.getAttribute('data-i18n-placeholder'),e=T[k]; if(!e) return;
    el.placeholder=e[lang];
  });
  html.setAttribute('lang',lang); html.setAttribute('dir',lang==='ar'?'rtl':'ltr');
  try{ localStorage.setItem('mm_lang',lang); }catch(e){}
  const flag=document.getElementById('langFlag');
  if(flag) flag.textContent=lang.toUpperCase();
  document.querySelectorAll('.lang-option').forEach(o=>o.classList.toggle('active',o.dataset.lang===lang));
  if(typeof authUser!=='undefined'&&authUser) setAuthUI(authUser);
  if(window.onLangChange) window.onLangChange(lang);
}
